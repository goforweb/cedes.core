// return the canonical url in JS, so the URL of the main object, useful when on a view
function canonical_url() {
  return $("link[rel='canonical']").attr('href');
}

function replaceListingContent(overrides) {

    var defaults = {};
    var url = canonical_url();
    url = url + '/get_common_result_listing';
    data = $.extend(defaults, overrides);
    $.ajax({
      url: url,
      dataType: 'html',
      data: data,
      cache: false,
      async: false,
      success: function(data) {
        var $container = $("#common-result-listing");
        $container.replaceWith(data);
        $('html, body').animate({
            scrollTop: $("#portal-column-content").offset().top
         }, 100);

        // fix up links generated by batching

        $("nav ul.pagination a").each(function(){
            $(this).attr("href", $(this).attr("href").replace(/get_common_result_listing/, ""));
        });
      },
      error: function(jqXHR, textStatus, errorThrown) {
        /*console.log(textStatus);*/
        window.location.href = window.location.href;
        }
    });
}

initListingNavigation = function () {
    /* folder listing table loading actions */
    $("#common-result-listing").delegate("nav ul.pagination a", "click", function(event) {
        event.preventDefault();
        var link = $(this).attr("href");
        var page = decodeURI((RegExp("b_start\:int" + '=' + '(.+?)(&|$)').exec(link)||[,null])[1]);

        replaceListingContent({ "b_start\:int": page });
        initListingNavigation();
    });
};

jQuery(document).ready(initListingNavigation);

// member delete confirm message
function confirmDeleteMember(member_id){
    if (confirm("Supprimer ce compte définitivement?")) {
        deleteMember(member_id); }
}

function deleteMember(member_id) {
  $.ajax({
    url: canonical_url() + "/@@member-delete",
    dataType: 'html',
    data: {'member_id': member_id, },
    cache: false,
    async: true,
    success: function(data) {
        location.reload();
    },
    error: function(jqXHR, textStatus, errorThrown) {
      /*console.log(textStatus);*/
      window.location.href = window.location.href;
      }
    });
}
